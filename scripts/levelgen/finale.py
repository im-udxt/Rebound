from lib import Level, emit_ts
# The Weight: a chase climb mixing every mechanic. No memories; the Weight rises from below.
L = Level(128)
def wind(h0, h1, a, b, ch):
    for h in range(h0, h1 + 1):
        for c in range(a, b + 1):
            if L.g[h][c] == '.': L.g[h][c] = ch
def mover_h(h, a, b, start, width=3):
    L.run(h, a, b, '-')
    for c in range(start, start + width): L.g[h][c] = 'H'
def mover_v(h_start, h_top, col, width=2):
    for h in range(h_start + 1, h_top + 1): L.put(h, col, '|')
    for c in range(col, col + width): L.put(h_start, c, 'V')
